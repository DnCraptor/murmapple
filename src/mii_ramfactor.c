static void MII_DEBUG_RAM_AE(const char* fmt, ...) {
    if (!fmt) return;
    /* format into a local buffer */
    char buf[256];
    va_list ap;
    va_start(ap, fmt);
    int n = vsnprintf(buf, sizeof(buf), fmt, ap);
    va_end(ap);
    if (n <= 0) return;
    /* clamp to buffer size */
    UINT len = (UINT)((n < (int)sizeof(buf)) ? n : (int)sizeof(buf) - 1);
    FIL f;
    FRESULT fr = f_open(&f, RAM_AF_LOG_PATH, FA_OPEN_ALWAYS | FA_WRITE | FA_OPEN_APPEND);
    if (fr != FR_OK) {
        return;
    }
    UINT wb = 0;
    f_write(&f, buf, len, &wb);
    f_close(&f);
}

